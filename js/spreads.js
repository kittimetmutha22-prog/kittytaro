const TH_MONTHS = ["มกราคม","กุมภาพันธ์","มีนาคม","เมษายน","พฤษภาคม","มิถุนายน","กรกฎาคม","สิงหาคม","กันยายน","ตุลาคม","พฤศจิกายน","ธันวาคม"];

function getSpread(type) {
  const now = new Date();
  const month = TH_MONTHS[now.getMonth()];
  const year = now.getFullYear() + 543;
  const spreads = {
    one: { title: "ไพ่ 1 ใบ", desc: "คำแนะนำสำหรับคุณในวันนี้", pos: ["คำแนะนำวันนี้"] },
    three: { title: "ไพ่ 3 ใบ", desc: "อดีต ปัจจุบัน และอนาคตของเรื่องที่ถาม", pos: ["อดีต", "ปัจจุบัน", "อนาคต"] },
    full: { title: "ดูแบบเต็ม (Celtic Cross)", desc: "วิเคราะห์สถานการณ์อย่างละเอียด 10 ใบ",
      pos: ["สถานการณ์ปัจจุบัน", "อุปสรรค / สิ่งที่ท้าทาย", "รากฐานของเรื่อง", "อดีตที่ผ่านมา", "เป้าหมาย / สิ่งที่หวัง", "อนาคตอันใกล้", "ตัวคุณ", "สิ่งแวดล้อม / คนรอบข้าง", "ความหวังและความกลัว", "ผลลัพธ์"] },
    monthly: { title: `ดวงรายเดือน ${month} ${year}`, desc: "ภาพรวมเดือนนี้ และคำทำนายรายสัปดาห์",
      pos: [`ภาพรวมเดือน${month}`, "สัปดาห์ที่ 1", "สัปดาห์ที่ 2", "สัปดาห์ที่ 3", "สัปดาห์ที่ 4"] },
    yearly: { title: `ดวงรายปี พ.ศ. ${year}`, desc: "ภาพรวมทั้งปี และคำทำนายทีละเดือน",
      pos: [`ภาพรวมปี ${year}`, ...TH_MONTHS] }
  };
  return spreads[type] || spreads.three;
}
